fn pct_encode_query_val(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 8);
    for b in s.bytes() {
        if b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_' | b'.' | b'~') {
            out.push(b as char);
        } else {
            let _ = write!(out, "%{b:02X}");
        }
    }
    out
}

fn inspect_obj_metrics(obj_path: &Path) -> ([f64; 3], u64) {
    let Ok(meta) = std::fs::symlink_metadata(obj_path) else {
        return ([1.0, 1.0, 1.0], 0);
    };
    if meta.file_type().is_symlink() || !meta.is_file() || meta.len() > MAX_MESH_BYTES {
        return ([1.0, 1.0, 1.0], 0);
    }
    let Ok(file) = std::fs::File::open(obj_path) else {
        return ([1.0, 1.0, 1.0], 0);
    };
    let mut reader = BufReader::new(file);
    let mut line = String::new();
    let mut min_v = [f64::INFINITY; 3];
    let mut max_v = [f64::NEG_INFINITY; 3];
    let mut any_v = false;
    let mut tris = 0u64;

    loop {
        line.clear();
        let Ok(n) = reader.read_line(&mut line) else {
            break;
        };
        if n == 0 {
            break;
        }
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("v ") {
            let mut nums = rest
                .split_whitespace()
                .filter_map(|s| s.parse::<f64>().ok().filter(|v| v.is_finite()));
            if let (Some(x), Some(y), Some(z)) = (nums.next(), nums.next(), nums.next()) {
                any_v = true;
                min_v[0] = min_v[0].min(x);
                min_v[1] = min_v[1].min(y);
                min_v[2] = min_v[2].min(z);
                max_v[0] = max_v[0].max(x);
                max_v[1] = max_v[1].max(y);
                max_v[2] = max_v[2].max(z);
            }
        } else if let Some(rest) = trimmed.strip_prefix("f ") {
            let verts = rest.split_whitespace().count();
            if verts >= 3 {
                tris += (verts - 2) as u64;
            }
        }
    }

    let size = if any_v {
        [
            ((max_v[0] - min_v[0]).abs().max(0.01) * 1000.0).round() / 1000.0,
            ((max_v[1] - min_v[1]).abs().max(0.01) * 1000.0).round() / 1000.0,
            ((max_v[2] - min_v[2]).abs().max(0.01) * 1000.0).round() / 1000.0,
        ]
    } else {
        [1.0, 1.0, 1.0]
    };
    (size, tris)
}

pub fn scan_project_meshes(dir: &Path, project_id: &str) -> Vec<Value> {
    let Ok(meshes_dir) = safe_project_path(dir, "assets/meshes") else {
        return Vec::new();
    };
    let Ok(dir_meta) = std::fs::symlink_metadata(&meshes_dir) else {
        return Vec::new();
    };
    if dir_meta.file_type().is_symlink() || !dir_meta.is_dir() {
        return Vec::new();
    }
    let manifest_val: Value = safe_project_path(dir, "assets/meshes/manifest.json")
        .ok()
        .filter(|p| {
            std::fs::symlink_metadata(p)
                .is_ok_and(|m| !m.file_type().is_symlink() && m.is_file() && m.len() <= MAX_MANIFEST_BYTES)
        })
        .and_then(|p| std::fs::read_to_string(p).ok())
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or_else(|| json!({}));

    let mut obj_files: Vec<String> = std::fs::read_dir(&meshes_dir)
        .ok()
        .into_iter()
        .flatten()
        .filter_map(|e| e.ok())
        .filter_map(|e| {
            let ft = e.file_type().ok()?;
            if ft.is_symlink() || !ft.is_file() {
                return None;
            }
            let p = e.path();
            if p.extension()
                .and_then(|ex| ex.to_str())
                .is_some_and(|ex| ex.eq_ignore_ascii_case("obj"))
            {
                Some(e.file_name().to_string_lossy().into_owned())
            } else {
                None
            }
        })
        .collect();
    obj_files.sort();

    let encoded_id = pct_encode_query_val(project_id);
    let mut out = Vec::with_capacity(obj_files.len());
    for fname in obj_files {
        let stem = fname
            .strip_suffix(".obj")
            .or_else(|| fname.strip_suffix(".OBJ"))
            .unwrap_or(&fname)
            .to_string();
        let obj_rel = format!("assets/meshes/{fname}");
        let obj_url = format!(
            "/api/projects/{encoded_id}/mesh-asset?path={}",
            pct_encode_query_val(&obj_rel)
        );

        let manifest_entry = manifest_val.as_object().and_then(|m| {
            m.get(&stem).or_else(|| {
                m.values().find(|v| {
                    v.get("mesh").and_then(|x| x.as_str()) == Some(fname.as_str())
                        || v.get("glow_mesh").and_then(|x| x.as_str()) == Some(fname.as_str())
                })
            })
        });

        let is_glow = manifest_entry
            .and_then(|e| e.get("glow_mesh").and_then(|x| x.as_str()))
            == Some(fname.as_str());

        let tex_candidate = manifest_entry
            .and_then(|e| {
                let key = if is_glow { "glow_texture" } else { "texture" };
                e.get(key).and_then(|x| x.as_str()).map(String::from)
            })
            .or_else(|| {
                ["png", "jpg", "jpeg", "mtl"].into_iter().find_map(|ext| {
                    let cand = format!("{stem}.{ext}");
                    let rel = format!("assets/meshes/{cand}");
                    safe_project_path(dir, &rel)
                        .ok()
                        .filter(|p| is_safe_regular_asset_file(dir, p))
                        .map(|_| cand)
                })
            });

        let texture_path = tex_candidate.and_then(|tex| resolve_mesh_texture_rel(dir, &tex));
        let texture_url = texture_path.as_ref().map(|tp| {
            format!(
                "/api/projects/{encoded_id}/mesh-asset?file={}",
                pct_encode_query_val(tp)
            )
        });

        let (computed_size, computed_tris) = inspect_obj_metrics(&meshes_dir.join(&fname));
        let size = if !is_glow {
            manifest_entry
                .and_then(|e| parse_vec3(e.get("size")))
                .unwrap_or(computed_size)
        } else {
            computed_size
        };
        let tris = manifest_entry
            .and_then(|e| {
                if is_glow {
                    e.get("glow_tris").and_then(|v| v.as_u64())
                } else {
                    e.get("solid_tris")
                        .or_else(|| e.get("tris"))
                        .and_then(|v| v.as_u64())
                }
            })
            .unwrap_or(computed_tris);

        out.push(json!({
            "name": stem,
            "obj_url": obj_url,
            "texture_url": texture_url,
            "size": size,
            "tris": tris,
            "obj_path": obj_rel,
            "texture_path": texture_path,
        }));
    }
    out
}

pub(crate) fn has_symlink_component(root: &Path, full: &Path) -> bool {
    let Ok(rel) = full.strip_prefix(root) else {
        return true;
    };
    let mut cur = root.to_path_buf();
    for comp in rel.components() {
        cur.push(comp);
        if let Ok(meta) = std::fs::symlink_metadata(&cur) {
            if meta.file_type().is_symlink() {
                return true;
            }
        }
    }
    false
}

fn is_safe_regular_asset_file(dir: &Path, full: &Path) -> bool {
    if has_symlink_component(dir, full) {
        return false;
    }
    let Ok(meta) = std::fs::symlink_metadata(full) else {
        return false;
    };
    if meta.file_type().is_symlink() || !meta.is_file() || meta.len() > MAX_MESH_BYTES {
        return false;
    }
    match (dir.canonicalize(), full.canonicalize()) {
        (Ok(cd), Ok(cf)) => cf.starts_with(&cd),
        _ => false,
    }
}

fn resolve_mesh_texture_rel(dir: &Path, raw: &str) -> Option<String> {
    let trimmed = raw.trim();
    if trimmed.is_empty()
        || trimmed.contains('\\')
        || trimmed.contains('\0')
        || trimmed.contains("://")
    {
        return None;
    }
    let clean = trimmed.trim_start_matches("./").trim_start_matches('/');
    let rel = if clean.starts_with("assets/meshes/") || clean.starts_with("art/") {
        clean.to_string()
    } else {
        format!("assets/meshes/{clean}")
    };
    let full = safe_project_path(dir, &rel).ok()?;
    let ext = full
        .extension()
        .and_then(|e| e.to_str())
        .map(|s| s.to_ascii_lowercase())?;
    if !matches!(ext.as_str(), "png" | "jpg" | "jpeg" | "mtl") {
        return None;
    }
    if is_safe_regular_asset_file(dir, &full) {
        Some(projects::rel_display(dir, &full))
    } else {
        None
    }
}

fn extract_str_or_content(v: Option<&Value>) -> Option<&str> {
    let v = v?;
    v.as_str()
        .or_else(|| v.get("Content").and_then(|c| c.as_str()))
}

/// Enrich `meshes[].texture_url` from `SurfaceAppearance` `ColorMap` children on matching `MeshPart`s.
pub fn enrich_meshes_with_surface_appearance(
    dir: &Path,
    project_id: &str,
    meshes: &mut [Value],
    services: &[Node],
) {
    fn collect_pairs(node: &Node, out: &mut Vec<(String, String)>) {
        if node.class == "MeshPart" {
            let mesh_id = extract_str_or_content(
                node.props.get("MeshId").or_else(|| node.props.get("mesh_id")),
            );
            if let Some(mid) = mesh_id {
                for child in &node.children {
                    if child.class == "SurfaceAppearance" {
                        if let Some(cm) = extract_str_or_content(
                            child
                                .props
                                .get("ColorMap")
                                .or_else(|| child.props.get("color_map")),
                        ) {
                            out.push((mid.to_string(), cm.to_string()));
                        }
                    }
                }
            }
        }
        for c in &node.children {
            collect_pairs(c, out);
        }
    }

    if meshes.is_empty() {
        return;
    }
    let mut pairs = Vec::new();
    for svc in services {
        collect_pairs(svc, &mut pairs);
    }
    if pairs.is_empty() {
        return;
    }

    let encoded_id = pct_encode_query_val(project_id);
    for mesh in meshes.iter_mut() {
        if !mesh["texture_url"].is_null() {
            continue;
        }
        let obj_path = mesh["obj_path"].as_str().unwrap_or("").to_ascii_lowercase();
        let obj_url = mesh["obj_url"].as_str().unwrap_or("").to_ascii_lowercase();
        let name = mesh["name"].as_str().unwrap_or("").to_ascii_lowercase();
        let fname = format!("{name}.obj");

        for (mid, cm) in &pairs {
            let mid_low = mid.trim().to_ascii_lowercase();
            let matches_mesh = (!obj_path.is_empty() && mid_low == obj_path)
                || (!obj_url.is_empty() && mid_low == obj_url)
                || (!name.is_empty() && (mid_low == name || mid_low.ends_with(&format!("/{fname}"))));
            if !matches_mesh {
                continue;
            }
            if let Some(rel) = resolve_mesh_texture_rel(dir, cm) {
                let url = format!(
                    "/api/projects/{encoded_id}/mesh-asset?file={}",
                    pct_encode_query_val(&rel)
                );
                if let Some(obj) = mesh.as_object_mut() {
                    obj.insert("texture_path".into(), json!(rel));
                    obj.insert("texture_url".into(), json!(url));
                }
                break;
            }
        }
    }
}

